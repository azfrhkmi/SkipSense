export interface NormalizedLandmark {
  x: number;
  y: number;
  z: number;
  visibility?: number;
}

export interface LandmarkResult {
  landmarks: NormalizedLandmark[];
  worldLandmarks?: NormalizedLandmark[];
}

export type JumpState = 'GROUNDED' | 'TAKEOFF' | 'AIRBORNE' | 'LANDING' | 'COUNTED';

export type WorkoutStatus =
  | 'IDLE'
  | 'CALIBRATING'
  | 'COUNTDOWN'
  | 'ACTIVE'
  | 'PAUSED'
  | 'TRACKING_LOST'
  | 'FINISHED';

export interface JumpDebugInfo {
  state: JumpState;
  hipY: number;
  ankleY: number;
  baselineHipY: number;
  displacementNorm: number;
  velocity: number;
  landmarkConfidence: number;
  isAirborne: boolean;
  lastJumpTime: number;
  threshold: number;
  fps: number;
}

export interface BodyPositionStatus {
  isFullyVisible: boolean;
  isCentered: boolean;
  isFacingCamera: boolean;
  isStable: boolean;
  message: string;
  confidence: number;
}

